#!/usr/bin/env python3
"""Converts the desktop line icons (apps/desktop/assets/icons/*.svg) to Android vector drawables
(res/drawable/ic_<name>.xml). Handles what the icons use: path, rect (with rx) and circle, with
fill and stroke attributes on the root or the element. Run from the repository root."""
import pathlib
import xml.etree.ElementTree as ET

SRC = pathlib.Path("apps/desktop/assets/icons")
OUT = pathlib.Path("apps/mobile/android/app/src/main/res/drawable")
NS = "{http://www.w3.org/2000/svg}"
PAINT = ("fill", "stroke", "stroke-width", "stroke-linecap", "stroke-linejoin")


def f(v: float) -> str:
    return f"{v:g}"


def geometry(el: ET.Element) -> str:
    tag = el.tag.removeprefix(NS)
    a = {k: float(v) for k, v in el.attrib.items() if k in ("x", "y", "width", "height", "rx", "cx", "cy", "r")}
    if tag == "path":
        return el.attrib["d"]
    if tag == "circle":
        cx, cy, r = a["cx"], a["cy"], a["r"]
        return f"M{f(cx - r)},{f(cy)}a{f(r)},{f(r)} 0 1,0 {f(2 * r)},0a{f(r)},{f(r)} 0 1,0 {f(-2 * r)},0Z"
    if tag == "rect":
        x, y, w, h, r = a.get("x", 0), a.get("y", 0), a["width"], a["height"], a.get("rx", 0)
        if not r:
            return f"M{f(x)},{f(y)}h{f(w)}v{f(h)}h{f(-w)}Z"
        return (f"M{f(x + r)},{f(y)}h{f(w - 2 * r)}a{f(r)},{f(r)} 0 0 1 {f(r)},{f(r)}v{f(h - 2 * r)}"
                f"a{f(r)},{f(r)} 0 0 1 {f(-r)},{f(r)}h{f(-(w - 2 * r))}a{f(r)},{f(r)} 0 0 1 {f(-r)},{f(-r)}"
                f"v{f(-(h - 2 * r))}a{f(r)},{f(r)} 0 0 1 {f(r)},{f(-r)}Z")
    raise SystemExit(f"unsupported element <{tag}>")


def convert(svg: pathlib.Path) -> str:
    root = ET.parse(svg).getroot()
    _, _, w, h = root.attrib["viewBox"].split()
    base = {k: root.attrib.get(k) for k in PAINT}
    paths = []
    for el in root.iter():
        if el.tag.removeprefix(NS) == "svg":
            continue
        p = {k: el.attrib.get(k, base[k]) for k in PAINT}
        attrs = [f'android:pathData="{geometry(el)}"']
        # Black only: Compose tints the icon.
        if p["fill"] not in (None, "none"):
            attrs.append('android:fillColor="#FF000000"')
        if p["stroke"] not in (None, "none"):
            attrs += ['android:strokeColor="#FF000000"', f'android:strokeWidth="{p["stroke-width"] or 1}"']
            if p["stroke-linecap"]:
                attrs.append(f'android:strokeLineCap="{p["stroke-linecap"]}"')
            if p["stroke-linejoin"]:
                attrs.append(f'android:strokeLineJoin="{p["stroke-linejoin"]}"')
        paths.append("    <path " + "\n        ".join(attrs) + " />")
    return (f"<!-- Generated by scripts/android-icons.py from {svg.as_posix()}. -->\n"
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{w}dp" android:height="{h}dp" android:viewportWidth="{w}" android:viewportHeight="{h}">\n'
            + "\n".join(paths) + "\n</vector>\n")


for svg in sorted(SRC.glob("*.svg")):
    (OUT / f"ic_{svg.stem.replace('-', '_')}.xml").write_text(convert(svg))
